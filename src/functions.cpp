// Функція 2: Перевірка, чи є число простим  
bool isPrime(int number) {
    // TODO: Реалізуйте цю функцію
    // Просте число - це натуральне число більше 1, яке ділиться тільки на 1 і на себе
    // Приклади: 2, 3, 5, 7, 11, 13, 17, 19, 23...
    // Не прості: 1, 4, 6, 8, 9, 10, 12, 14, 15, 16, 18, 20...
    
    if (number <= 1) {
        return false; // Числа <= 1 не є простими
    }
    
    if (number == 2) {
        return true; // 2 - єдине парне просте число
    }
    
    // Замініть це на правильну реалізацію
    return false;
}

