#ifndef FUNCTIONS_H
#define FUNCTIONS_H

// Функція 1: Обчислення факторіалу числа
// Факторіал n! = 1 * 2 * 3 * ... * n
// Для n = 0 або n = 1, результат = 1
// Для від'ємних чисел поверніть 0
long long factorial(int n);

// Функція 2: Перевірка, чи є число простим
// Просте число - це натуральне число більше 1, яке ділиться тільки на 1 і на себе
// Поверніть true, якщо число просте, false - якщо ні
bool isPrime(int number);

// Функція 3: Знаходження найбільшого спільного дільника (НСД) двох чисел
// Використайте алгоритм Евкліда для знаходження НСД
// НСД(a, 0) = a; НСД(a, b) = НСД(b, a % b)
int gcd(int a, int b);

#endif // FUNCTIONS_H